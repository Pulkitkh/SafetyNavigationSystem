// Turns drizzle-kit's generated SQL (drizzle/*.sql) into src/lib/db/migrate.ts:
// a script that is safe to run on every start. Tables, indexes and foreign keys
// are created only if missing, and every column is also added to existing
// tables, so a deploy with new columns upgrades the live database by itself.
//   npm run db:generate
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const files = readdirSync("drizzle").filter((f) => f.endsWith(".sql")).sort();
const statements = files.flatMap((f) => readFileSync(`drizzle/${f}`, "utf8").split("--> statement-breakpoint")).map((s) => s.trim()).filter(Boolean);

const out = [];
const addColumns = [];
for (const s of statements) {
  if (s.startsWith("CREATE SCHEMA")) out.push(s.replace("CREATE SCHEMA", "CREATE SCHEMA IF NOT EXISTS"));
  else if (s.startsWith("CREATE TABLE")) {
    out.push(s.replace("CREATE TABLE", "CREATE TABLE IF NOT EXISTS"));
    const table = s.match(/^CREATE TABLE ("[^"]+"\."[^"]+")/)[1];
    const body = s.slice(s.indexOf("(") + 1, s.lastIndexOf(")"));
    for (const line of body.split("\n").map((l) => l.trim().replace(/,$/, ""))) {
      if (!line.startsWith('"')) continue; // table constraints
      let def = line.replace(" PRIMARY KEY", "");
      // A new NOT NULL column needs a default, or it can't be added to a table with rows.
      if (/ NOT NULL/.test(def) && !/ DEFAULT /.test(def)) def = def.replace(" NOT NULL", "");
      addColumns.push(`ALTER TABLE ${table} ADD COLUMN IF NOT EXISTS ${def};`);
    }
  } else if (s.startsWith("ALTER TABLE") && s.includes("ADD CONSTRAINT")) {
    out.push(`DO $$ BEGIN\n  ${s}\nEXCEPTION WHEN duplicate_object OR duplicate_table THEN NULL;\nEND $$;`);
  } else if (/^CREATE (UNIQUE )?INDEX/.test(s)) out.push(s.replace(/^CREATE (UNIQUE )?INDEX/, (m) => `${m} IF NOT EXISTS`));
  else throw new Error(`Unhandled statement: ${s.slice(0, 80)}`);
}

const sql = [...out.slice(0, 1), ...out.slice(1).filter((s) => s.startsWith("CREATE TABLE")), ...addColumns, ...out.slice(1).filter((s) => !s.startsWith("CREATE TABLE"))]
  .map((s) => (s.endsWith(";") || s.endsWith("$$;") ? s : `${s};`))
  .join("\n");

writeFileSync(
  "src/lib/db/migrate.ts",
  `// Generated by scripts/build-migration.mjs from drizzle-kit output. Do not edit by hand:
// change schema.ts, then run \`npm run db:generate\`.
// Safe to run on every start; see the script for how it stays idempotent.
export const MIGRATION_SQL = \`
${sql.replace(/`/g, "\\`")}
\`;
`,
);
console.log(`migrate.ts: ${out.length} statements, ${addColumns.length} column checks`);
